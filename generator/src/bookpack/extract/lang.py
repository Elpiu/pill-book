def detect_lang(text: str, default: str = "en") -> str:
    words = text.lower().split()
    if not words:
        return default
    scores = {
        lang: sum(word in set(stopwords) for word in words)
        for lang, stopwords in _STOPWORDS.items()
    }
    return max(scores, key=lambda lang: scores[lang])
